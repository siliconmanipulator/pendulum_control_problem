function style_problem_1(f)
% Presentation only: dark theme and typeset mathematical labels.
set(f,'Theme','dark','Color',[.10 .11 .14]);
ax=findall(f,'Type','axes');
for a=ax'
 set(a,'Color',[.075 .085 .105],'XColor',[.86 .88 .92],'YColor',[.86 .88 .92]);
end
tx=findall(f,'Type','text');
old={'theta (rad)','theta (rad, unwrapped)','theta dot (rad/s)', ...
 'y = theta dot (rad/s)','theta','E/(m l^2)','Potential/(m l^2)', ...
 'I: pi/6, 0','II: 0, pi/omega','III: pi/2, 0', ...
 'IV: 2pi+epsilon, 0','V: 2pi-epsilon, 0','VI: 0, 0'};
new={'$\theta$ (rad)','$\theta$ (rad, unwrapped)','$\dot{\theta}$ (rad/s)', ...
 '$y=\dot{\theta}$ (rad/s)','$\theta$','$E/(ml^2)$','$V/(ml^2)$', ...
 'I: $\theta_0=\pi/6,\ \dot{\theta}_0=0$', ...
 'II: $\theta_0=0,\ \dot{\theta}_0=\pi/\omega$', ...
 'III: $\theta_0=\pi/2,\ \dot{\theta}_0=0$', ...
 'IV: $\theta_0=2\pi+\epsilon,\ \dot{\theta}_0=0$', ...
 'V: $\theta_0=2\pi-\epsilon,\ \dot{\theta}_0=0$', ...
 'VI: $\theta_0=0,\ \dot{\theta}_0=0$'};
for h=tx'
 set(h,'Color',[.91 .93 .97]);s=h.String;
 if ischar(s)
  idx=find(strcmp(s,old),1);
  if ~isempty(idx),set(h,'String',new{idx},'Interpreter','latex');end
  if startsWith(s,'theta=')
   s=regexprep(s,'theta=([^|]+) \| y=(.*)','$\\theta=$1 | $y=\\dot{\\theta}=$2');
   set(h,'String',s,'Interpreter','latex');
  end
 elseif iscell(s) && ~isempty(s) && strcmp(s{1},'PROBLEM 1 - nonlinear pendulum')
  set(h,'String',{'PROBLEM 1 -- nonlinear pendulum', ...
   '$ml^2\ddot{\theta}+mgl\sin\theta=\tau(t)$', ...
   '$u=\tau/(ml^2),\quad g/l=10$', ...
   '$x_1=\theta,\quad x_2=\dot{\theta}=y$', ...
   '$\dot{x}_1=x_2$', '$\dot{x}_2=u-10\sin x_1$', ...
   'Part (b): unit step $u=1$', ...
   'Part (c): pulse area $J=0.1,\ldots,1$ rad/s', ...
   '$\epsilon=0.05$ rad; normalized model', ...
   'Original equilibrium question: $u=0$', ...
   'Undamped: oscillations do not decay'},'Interpreter','latex');
 elseif iscell(s) && ~isempty(s) && strcmp(s{1},'PART (e): EQUILIBRIA')
  set(h,'String',{'PART (e): EQUILIBRIA', ...
   '$u=0:\quad (\theta_*,\dot{\theta}_*)=(k\pi,0)$', ...
   '$\theta_*=2k\pi:\quad\lambda=\pm i\sqrt{10}$', ...
   'Stable centers; not asymptotically stable', ...
   '$\theta_*=(2k+1)\pi:\quad\lambda=\pm\sqrt{10}$', ...
   'Unstable saddles', ...
   '$u=1:\quad\alpha=\sin^{-1}(0.1)=0.100167$ rad', ...
   'Centers: $\alpha+2k\pi$', ...
   'Saddles: $\pi-\alpha+2k\pi$', ...
   'Case VI: the unit step excites motion'},'Interpreter','latex');
 end
end
% Brighten explicitly dark output curves without changing trajectory data.
ll=findall(f,'Type','line');
for h=ll'
 if isnumeric(h.Color) && isequal(h.Color,[.25 .25 .25]),h.Color=[.87 .89 .93];end
 if isnumeric(h.Color) && isequal(h.Color,[0 0 0]),h.Color=[.85 .87 .92];end
 if isprop(h,'MarkerFaceColor') && isnumeric(h.MarkerFaceColor) && isequal(h.MarkerFaceColor,[0 0 0]),h.MarkerFaceColor=[.85 .87 .92];end
end
ann=findall(f,'Type','textboxshape');
for h=ann'
 h.Color=[.91 .93 .97];
 if isnumeric(h.BackgroundColor),h.BackgroundColor=[.16 .20 .27];end
 if strcmp(h.String,'u -> SUM -> integral -> x2 = y -> integral -> x1 = theta')
  h.String='$u\ \longrightarrow\ \Sigma\ \longrightarrow\ \int\ \longrightarrow\ x_2=y\ \longrightarrow\ \int\ \longrightarrow\ x_1=\theta$';h.Interpreter='latex';
 elseif strcmp(h.String,'1/s : x2'),h.String='$1/s:\ x_2$';h.Interpreter='latex';
 elseif strcmp(h.String,'1/s : x1'),h.String='$1/s:\ x_1$';h.Interpreter='latex';
 elseif strcmp(h.String,'10 sin(x1)'),h.String='$10\sin(x_1)$';h.Interpreter='latex';
 end
end
for typ={'arrow','line'}
 hh=findall(f,'Type',[typ{1} 'shape']);for h=hh',h.Color=[.85 .88 .94];end
end
drawnow;
end
